"""Schema validation and deterministic argument matching metrics (F7).

Validates model-generated tool arguments against JSON Schema definitions using
jsonschema, computes primary strict-match argument metrics (allowing optional extra keys),
and scores partial argument overlaps.
"""

from __future__ import annotations

import logging
from typing import Any

import jsonschema

logger = logging.getLogger(__name__)


def normalize_value(val: Any) -> Any:
    """Normalize a value for deterministic comparison.

    Rules:
    - String: Strip leading/trailing whitespace. Case is preserved (case-strict).
    - Bool: Preserved as bool (distinct from ints).
    - Number: int and float with equal value compare as equal (5 == 5.0).
    - Dict: Recursively normalize values, sorted by key.
    - List: Recursively normalize elements.
    """
    if isinstance(val, bool):
        return val
    if isinstance(val, (int, float)):
        # Normalize -0.0 to 0.0
        return 0.0 if val == 0 else float(val)
    if isinstance(val, str):
        return val.strip()
    if isinstance(val, dict):
        return {str(k).strip(): normalize_value(v) for k, v in sorted(val.items())}
    if isinstance(val, (list, tuple)):
        return [normalize_value(x) for x in val]
    return val


def values_are_equal(v1: Any, v2: Any) -> bool:
    """Return True if two normalized values are semantically equal."""
    # Ensure booleans are not treated as equal to numeric 1 or 0
    if isinstance(v1, bool) != isinstance(v2, bool):
        return False
    return normalize_value(v1) == normalize_value(v2)


def validate_schema(
    schema: dict[str, Any],
    arguments: dict[str, Any],
) -> tuple[bool, str | None]:
    """Validate tool arguments against the tool's JSON Schema.

    Args:
        schema: Tool parameter JSON Schema (e.g. from ToolInfo.input_schema).
        arguments: Arguments dictionary generated by the LLM.

    Returns:
        Tuple of (is_valid: bool, error_message: str | None).
    """
    if not schema or not isinstance(schema, dict):
        return True, None

    # If schema defines no properties or restrictions, empty object is valid
    try:
        validator_cls = jsonschema.validators.validator_for(schema)
        validator = validator_cls(schema)
        errors = sorted(validator.iter_errors(arguments), key=lambda e: e.path)
        if not errors:
            return True, None

        first_error = errors[0]
        field_path = ".".join(str(p) for p in first_error.path)
        prefix = f"Field '{field_path}': " if field_path else ""
        return False, f"{prefix}{first_error.message}"
    except Exception as err:
        logger.warning("Unexpected error during schema validation: %s", err)
        return False, str(err)


def compute_args_strict_match(
    acceptable_args: list[dict[str, Any]],
    chosen_args: dict[str, Any],
) -> tuple[bool, bool]:
    """Compute primary args_strict_match metric and extra keys detection.

    An execution is an `args_strict_match` if there exists at least one acceptable
    argument set A in `acceptable_args` such that every key in A is present in
    `chosen_args` and their normalized values match. Extra keys in `chosen_args`
    not defined in A are ignored for the match, but recorded in `has_extra_keys`.

    Args:
        acceptable_args: List of valid ground-truth argument dictionaries.
        chosen_args: Actual argument dictionary generated by the LLM.

    Returns:
        Tuple of (is_strict_match: bool, chosen_args_has_extra_keys: bool).
    """
    if not acceptable_args:
        # If no expected args defined, matching an empty dict is true if chosen is empty
        is_match = len(chosen_args) == 0
        return is_match, len(chosen_args) > 0

    best_match = False
    has_extra = False

    for candidate in acceptable_args:
        cand_keys = set(candidate.keys())
        chosen_keys = set(chosen_args.keys())

        # Check if all keys in candidate are present in chosen_args with equal values
        all_keys_match = True
        for k, v in candidate.items():
            if k not in chosen_args:
                all_keys_match = False
                break
            if not values_are_equal(chosen_args[k], v):
                all_keys_match = False
                break

        if all_keys_match:
            best_match = True
            extra_keys_in_this = chosen_keys - cand_keys
            if extra_keys_in_this:
                has_extra = True
            # Found at least one valid acceptable arg match
            break

    # If no candidate matched completely, check if extra keys exist relative to candidates
    if not best_match:
        # Detect if chosen has keys beyond the union of all acceptable keys
        all_possible_keys = set().union(*(c.keys() for c in acceptable_args))
        has_extra = bool(set(chosen_args.keys()) - all_possible_keys)

    return best_match, has_extra


def compute_args_match_score(
    acceptable_args: list[dict[str, Any]],
    chosen_args: dict[str, Any],
    tool_correct: bool,
) -> float:
    """Compute heuristic fractional argument match score.

    Formula:
        score(A) = matched_keys / len(A)  (if len(A) == 0, score = 1.0)
        Returns max(score(A)) across all A in acceptable_args.
        Returns 0.0 if tool_correct is False or acceptable_args is empty.

    Args:
        acceptable_args: List of valid ground-truth argument sets.
        chosen_args: Actual argument dictionary generated by the LLM.
        tool_correct: Boolean indicating whether the chosen tool matched the expected tool.

    Returns:
        Float score in range [0.0, 1.0].
    """
    if not tool_correct or not acceptable_args:
        return 0.0

    best_score = 0.0
    for candidate in acceptable_args:
        if not candidate:
            score = 1.0 if not chosen_args else 1.0
            best_score = max(best_score, score)
            continue

        matched_count = 0
        for k, v in candidate.items():
            if k in chosen_args and values_are_equal(chosen_args[k], v):
                matched_count += 1

        score = matched_count / len(candidate)
        best_score = max(best_score, score)

    return float(best_score)
